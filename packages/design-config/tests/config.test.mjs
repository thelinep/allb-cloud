import assert from 'node:assert/strict';
import {defaults,parseConfig,resolveDesign,safeAsset,contrast} from '../config.ts';
const c=structuredClone(defaults);
c.brands.nevo={theme:{accent:'#e7bcd7'},branding:{name:'NEVO'}};
c.routes['/allb/*']={theme:{radius:20}};
c.routes['/allb/nevo']={brand:'nevo',theme:{accent:'#ffffff'}};
parseConfig(c);
assert.equal(resolveDesign(c,'/allb/nevo').branding.name,'NEVO');
assert.equal(resolveDesign(c,'/workspace/nevo').branding.name,'NEVO');
assert.equal(resolveDesign(c,'/workspace/nevo').theme.accent,'#e7bcd7');
assert.equal(resolveDesign(c,'/allb/nevo').theme.accent,'#ffffff');
assert.equal(resolveDesign(c,'/allb/new-product').theme.radius,20);
assert.equal(resolveDesign(c,'/unrelated').theme.radius,12);
assert.equal(resolveDesign(c,'/allbirds').theme.radius,12);
c.routes['/allb/nevo/*']={theme:{radius:30}};
assert.equal(resolveDesign(c,'/allb/nevo/booking').theme.radius,30);
assert.equal(resolveDesign(c,'/allb/nevo/booking').branding.name,'MAATAA UI');
c.routes['/allb/nevo/*'].brand='nevo';
assert.equal(resolveDesign(c,'/allb/nevo/booking').branding.name,'NEVO');
assert.equal(safeAsset('javascript:alert(1)'),false);
assert.equal(safeAsset('//evil.example/x'),false);
assert.equal(safeAsset('/assets/logo.webp'),true);
assert.equal(contrast('#000000','#ffffff'),21);
assert.throws(()=>parseConfig({...c,schemaVersion:2}));
assert.throws(()=>parseConfig({...c,routes:{'/x':{brand:'missing'}}}));
assert.throws(()=>parseConfig({...c,brands:{nevo:{theme:{mode:['dark']}}}}));
assert.throws(()=>parseConfig({...c,brands:{nevo:{branding:{logo:'data:image/svg+xml,test'}}}}));
assert.throws(()=>parseConfig({...c,routes:{'/x':{theme:{radius:Infinity}}}}));
assert.equal(JSON.stringify(parseConfig(JSON.parse(JSON.stringify(c)))),JSON.stringify(c));
const before=JSON.stringify(c);resolveDesign(c,'/allb/nevo');assert.equal(JSON.stringify(c),before);
console.log('PASS: inheritance, wildcard specificity, future routes, scoped branding, nonmutation, schema validation, asset URLs, contrast and JSON roundtrip');
