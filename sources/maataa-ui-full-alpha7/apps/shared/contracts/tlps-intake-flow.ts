/**
 * First TLPS flow: idea → reviewable Brahmini proposal → preview → explicit
 * user approval → TLPS project record → event history.
 *
 * Boundaries:
 * - A proposal is either a SYNTHETIC DEMO template (deterministic, no model)
 *   or a PROVIDER DRAFT (text a configured Brahmini provider returned). Both
 *   are labelled as drafts; neither is a "generated production script".
 * - Nothing is written until `decideIntakeProposal` receives an approval
 *   whose digest matches the exact previewed record.
 * - An existing TLPS draft with any content is preserved: approval fails
 *   closed instead of overwriting it.
 * - Only metadata (title, type, idea, logline) enters the record; the
 *   proposal cannot carry budgets, crew, locations or schedules.
 */
import type { TlpsDraft, TlpsProjectType } from "../../tlps/src/types.ts";
import {
  appendProjectEvent,
  type ProjectEventEnvelope,
} from "./project-events.ts";

export const TLPS_INTAKE_SCOPE = "tlps:intake";
export const SYNTHETIC_PROPOSAL_LABEL = "Synthetic demo proposal: a fixed template, not generated by a model.";
export const PROVIDER_DRAFT_LABEL = "Provider draft: review before use. This is not a production script.";

export type ProposalOrigin =
  | { kind: "synthetic-demo" }
  | { kind: "provider-draft"; provider: string; model: string };

export interface IntakeProposal {
  proposalVersion: 1;
  idea: string;
  title: string;
  productionType: TlpsProjectType;
  logline: string;
  origin: ProposalOrigin;
  label: string;
}

export interface IntakePreview {
  proposal: IntakeProposal;
  /** Exactly what approval would write. */
  record: TlpsDraft;
  proposalDigest: string;
  conflict: "existing-tlps-draft" | null;
}

export type IntakeDecision =
  | { decision: "approve"; proposalDigest: string; decidedBy: "local-user" }
  | { decision: "reject"; proposalDigest: string; decidedBy: "local-user" };

export interface IntakeOutcome {
  record: TlpsDraft | null;
  events: ProjectEventEnvelope[];
}

const PROVIDER_ID = /^[a-z][a-z0-9-]{1,31}$/;
const MODEL_ID = /^[A-Za-z0-9][A-Za-z0-9._:/-]{0,79}$/;

function clean(value: string, max: number) {
  return value.replace(/\s+/g, " ").trim().slice(0, max);
}

function validateIdea(idea: string) {
  const text = clean(idea, 500);
  if (text.length < 3) throw new Error("Describe the idea in at least 3 characters.");
  return text;
}

/** Deterministic template. Exists so the flow can be rehearsed without any provider. */
export function createSyntheticProposal(
  idea: string,
  projectTypes: readonly TlpsProjectType[],
): IntakeProposal {
  const text = validateIdea(idea);
  const lower = text.toLowerCase();
  const productionType =
    projectTypes.find((type) => lower.includes(type.toLowerCase()))
    ?? (projectTypes.includes("Short Film" as TlpsProjectType) ? ("Short Film" as TlpsProjectType) : projectTypes[0]);
  if (!productionType) throw new Error("No TLPS project types are available.");
  const words = text.split(" ").slice(0, 6).join(" ");
  return {
    proposalVersion: 1,
    idea: text,
    title: clean(`Draft: ${words}`, 120),
    productionType,
    logline: clean(text, 280),
    origin: { kind: "synthetic-demo" },
    label: SYNTHETIC_PROPOSAL_LABEL,
  };
}

/** Wraps fields a Brahmini provider returned, after bounding and validating them. */
export function createProviderDraftProposal(
  idea: string,
  fields: { title: string; productionType: string; logline: string },
  origin: { provider: string; model: string },
  projectTypes: readonly TlpsProjectType[],
): IntakeProposal {
  const text = validateIdea(idea);
  if (!PROVIDER_ID.test(origin.provider) || !MODEL_ID.test(origin.model)) throw new Error("Unknown provider or model identifier.");
  const productionType = projectTypes.find((type) => type === fields.productionType);
  if (!productionType) throw new Error("The draft proposed a project type TLPS does not support.");
  const title = clean(fields.title, 120);
  if (!title) throw new Error("The draft has no title.");
  return {
    proposalVersion: 1,
    idea: text,
    title,
    productionType,
    logline: clean(fields.logline, 280),
    origin: { kind: "provider-draft", provider: origin.provider, model: origin.model },
    label: PROVIDER_DRAFT_LABEL,
  };
}

export function hasTlpsContent(draft: TlpsDraft): boolean {
  return Boolean(
    draft.project.title.trim()
    || draft.project.idea?.trim()
    || draft.budget.length
    || draft.crew.length
    || draft.locations.length
    || draft.schedule.length
    || draft.evidence.length
    || draft.activity.length
    || draft.status !== "draft",
  );
}

function canonical(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map(canonical).join(",")}]`;
  if (value && typeof value === "object") {
    return `{${Object.keys(value as Record<string, unknown>).sort()
      .map((key) => `${JSON.stringify(key)}:${canonical((value as Record<string, unknown>)[key])}`).join(",")}}`;
  }
  return JSON.stringify(value);
}

async function sha256(text: string) {
  const bytes = new Uint8Array(await globalThis.crypto.subtle.digest("SHA-256", new TextEncoder().encode(text)));
  return `sha256:${Array.from(bytes, (byte) => byte.toString(16).padStart(2, "0")).join("")}`;
}

/**
 * Builds the preview. `baseDraft` should be TLPS's `emptyTlpsDraft` and
 * `existingDraft` the result of `readTlpsDraft(localStorage…)`.
 */
export async function previewIntakeRecord(
  proposal: IntakeProposal,
  baseDraft: TlpsDraft,
  existingDraft: TlpsDraft | null,
): Promise<IntakePreview> {
  const record: TlpsDraft = {
    ...baseDraft,
    project: {
      title: proposal.title,
      idea: proposal.idea,
      city: baseDraft.project.city,
      productionType: proposal.productionType,
      shootDate: baseDraft.project.shootDate,
      ceiling: baseDraft.project.ceiling,
    },
    budget: [],
    crew: [],
    locations: [],
    schedule: [],
    status: "draft",
    approvalNote: "",
    evidence: [],
    activity: [],
  };
  return {
    proposal,
    record,
    proposalDigest: await sha256(canonical({ proposal, record })),
    conflict: existingDraft && hasTlpsContent(existingDraft) ? "existing-tlps-draft" : null,
  };
}

/**
 * Applies the user's decision. Approval requires the digest of the exact
 * preview and no conflict; rejection writes no record but is logged.
 */
export async function decideIntakeProposal(
  preview: IntakePreview,
  decision: IntakeDecision,
  log: readonly ProjectEventEnvelope[],
  now: () => number = Date.now,
): Promise<IntakeOutcome> {
  const recomputed = await sha256(canonical({ proposal: preview.proposal, record: preview.record }));
  if (recomputed !== preview.proposalDigest) throw new Error("The preview changed after it was shown. Review it again.");
  if (decision.proposalDigest !== preview.proposalDigest) throw new Error("This approval is for a different preview.");
  const evidence = preview.proposal.origin.kind === "provider-draft" ? "provider-draft" : "synthetic-demo";
  const project = { id: "tlps:workspace", product: "tlps" } as const;
  const payload = { title: preview.proposal.title, projectType: preview.proposal.productionType, proposalDigest: preview.proposalDigest };
  let events = appendProjectEvent(log, TLPS_INTAKE_SCOPE, {
    project,
    source: { app: "brahmini", component: "tlps-intake-proposal" },
    actor: { kind: "brahmini-proposal", id: preview.proposal.origin.kind },
    action: "proposal-created",
    evidence,
    payload,
  }, now);

  if (decision.decision === "reject") {
    events = appendProjectEvent(events, TLPS_INTAKE_SCOPE, {
      project,
      source: { app: "tlps", component: "intake-review" },
      actor: { kind: "local-user", id: "local-user" },
      action: "proposal-rejected",
      evidence,
      payload: { proposalDigest: preview.proposalDigest },
    }, now);
    return { record: null, events };
  }
  if (preview.conflict) throw new Error("An existing TLPS project is open. It was preserved; nothing was written.");

  events = appendProjectEvent(events, TLPS_INTAKE_SCOPE, {
    project,
    source: { app: "tlps", component: "intake-review" },
    actor: { kind: "local-user", id: "local-user" },
    action: "proposal-approved",
    evidence,
    payload: { proposalDigest: preview.proposalDigest },
  }, now);
  events = appendProjectEvent(events, TLPS_INTAKE_SCOPE, {
    project,
    source: { app: "tlps", component: "intake-review" },
    actor: { kind: "local-user", id: "local-user" },
    action: "record-created",
    evidence,
    payload: { title: preview.record.project.title, projectType: preview.record.project.productionType, status: "draft" },
  }, now);
  return { record: structuredClone(preview.record), events };
}
